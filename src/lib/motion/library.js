const EX = {};
const LAD = {};
/* [id, name, eq[], kind, goal, met, animId, animParams, cue, per] kind: reps | hold | time */
function ladder(id, name, fam, list) {
  LAD[id] = { id, name, fam, ids: [] };
  list.forEach((r) => {
    const [eid, ename, eq, kind, goal, met, anim, params, cue, per] = r;
    const start =
      kind === 'reps'
        ? Math.max(3, Math.round(goal * 0.5))
        : kind === 'hold'
          ? Math.max(8, Math.round((goal * 0.5) / 5) * 5)
          : goal;
    EX[eid] = {
      id: eid,
      name: ename,
      ladder: id,
      fam,
      eq,
      kind,
      goal,
      start,
      met,
      anim,
      params: params || {},
      cue,
      per: !!per,
      idx: LAD[id].ids.length,
    };
    LAD[id].ids.push(eid);
  });
}
